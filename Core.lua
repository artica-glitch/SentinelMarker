panel:SetClampedToScreen(true)
panel:SetMovable(true)
panel:EnableMouse(true)
panel:RegisterForDrag("LeftButton")
panel:SetScript("OnDragStart", function(self)
    if not InCombatLockdown() then self:StartMoving() end
end)
panel:SetScript("OnDragStop", function(self)
    if InCombatLockdown() then return end
    self:StopMovingOrSizing()
    local point, _, relativePoint, x, y = self:GetPoint()
    SentinelMarkersDB = SentinelMarkersDB or {}
    SentinelMarkersDB.position = {point, relativePoint, x, y}
end)
panel:SetBackdrop({bgFile = "Interface\\Buttons\\WHITE8X8", edgeFile = "Interface\\Buttons\\WHITE8X8", edgeSize = 1})
panel:SetBackdropColor(0.025, 0.04, 0.07, 0.93)
panel:SetBackdropBorderColor(0.15, 0.5, 0.95, 1)
local title = panel:CreateFontString(nil, "OVERLAY", "GameFontNormal")
title:SetPoint("TOP", 0, -10)
local function Refresh()
    title:SetText(SentinelMarkerInfo.displayName)
    if not InCombatLockdown() then panel:SetShown(active or preview) end
end
for i = 1, 3 do
    local button = CreateFrame("Button", "EntombedBlue" .. i, panel, "SecureActionButtonTemplate,UIPanelButtonTemplate")
    button:SetSize(70, 42)
    button:SetPoint("TOPLEFT", 12 + (i - 1) * 79, -34)
    button:RegisterForClicks("AnyDown", "AnyUp")
