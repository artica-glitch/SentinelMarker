local function Info(message)
    print("|cff3399ffSentinel Marker:|r " .. message)
end
local function Message(number)
    local marker = "{rt" .. markers[number] .. "}"
    return marker .. " " .. number .. " " .. marker
end
local buttons = {}
local pendingSetup, pendingClose = false, false
local setupBusy = false
local loginReady = false
local function NormalizeMacroBody(body)
    if type(body) ~= "string" then return nil end
    return body:gsub("\r\n", "\n"):gsub("\r", "\n"):match("^%s*(.-)%s*$")
end
local function SetupMacros()
    if setupBusy then return end
    if not loginReady then pendingSetup = true; return end
    if InCombatLockdown() then pendingSetup = true; return end
    pendingSetup = false
    setupBusy = true
    for i = 1, 3 do
        local name = "ESMark" .. i
        local body = "/yell " .. Message(i)
        local index = GetMacroIndexByName(name)
        if index == 0 then
            local ok, result = pcall(CreateMacro, name, SentinelMarkerInfo.icon, body, false)
            if ok and type(result) == "number" then index = result end
        end
        local valid = false
        if index and index > 0 then
            local _, _, existing = GetMacroInfo(index)
            -- Upgrade only the exact SAY macro generated by earlier versions.
            if NormalizeMacroBody(existing) == "/say " .. Message(i) then
                local ok = pcall(EditMacro, index, nil, nil, body)
                if ok then _, _, existing = GetMacroInfo(index) end
            end
            valid = NormalizeMacroBody(existing) == body
            if valid then
                local _, currentIcon = GetMacroInfo(index)
                if currentIcon ~= SentinelMarkerInfo.icon then
                    pcall(EditMacro, index, nil, SentinelMarkerInfo.icon)
                end
            end
        end
        -- Resolve by stable name in the secure handler; macro indices may move.
        buttons[i]:SetAttribute("macro", valid and name or nil)
        if not valid then
            Info(L.MACRO:format(name))
        end
    end
    setupBusy = false
end

local function RecheckAfterLoad()
    SetupMacros()
    if C_Timer and C_Timer.After then
        C_Timer.After(0, SetupMacros)
        C_Timer.After(.5, SetupMacros)
    end
end

