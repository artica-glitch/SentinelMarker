local events = CreateFrame("Frame")
for _, event in ipairs({"PLAYER_LOGIN", "ENCOUNTER_START", "ENCOUNTER_END", "PLAYER_ENTERING_WORLD", "PLAYER_REGEN_DISABLED", "PLAYER_REGEN_ENABLED", "UPDATE_MACROS"}) do
    events:RegisterEvent(event)
end
events:SetScript("OnEvent", function(_, event, encounterID)
    if event == "PLAYER_LOGIN" then
        loginReady = true
        SentinelMarkersDB = SentinelMarkersDB or {}
        SentinelMarkersDB.scale = nil
        panel:SetScale(1)
        local pos = SentinelMarkersDB.position
        if type(pos) == "table" and type(pos[1]) == "string" and type(pos[2]) == "string" and type(pos[3]) == "number" and type(pos[4]) == "number" then
            panel:ClearAllPoints()
            panel:SetPoint(pos[1], UIParent, pos[2], pos[3], pos[4])
        end
        RecheckAfterLoad()
        Info(L.PREP)
    elseif event == "ENCOUNTER_START" then
        if issecretvalue and issecretvalue(encounterID) then
            active = false
            Info(L.SECRET_ID)
        else
            active = encounterID == ENCOUNTER_ID
        end
        if active and InCombatLockdown() and not panel:IsShown() then
            Info(L.CLOSED)
        end
    elseif event == "ENCOUNTER_END" or event == "PLAYER_ENTERING_WORLD" then
        active = false
        preview = false
        pendingClose = InCombatLockdown() and true or false
        if event == "PLAYER_ENTERING_WORLD" then RecheckAfterLoad() end
    elseif event == "PLAYER_REGEN_ENABLED" then
        if pendingSetup then SetupMacros() end
        if pendingClose then active = false; preview = false; pendingClose = false end
    elseif event == "UPDATE_MACROS" then
        SetupMacros()
    end
    Refresh()
end)

SLASH_ENTOMBEDBLUE1 = "/sm"
SlashCmdList.ENTOMBEDBLUE = function(message)
    message = message:lower():match("^%s*(.-)%s*$")
    if message == "version" or message == "ver" then
        Info(SentinelMarkerInfo.displayName .. " (" .. SentinelMarkerInfo.name .. ")")
    elseif message == "config" or message == "options" then
        SentinelOpenOptions()
    elseif message == "setup" then
        SetupMacros()
    elseif message == "test" or message == "" or message == "config" then
        if InCombatLockdown() or active then Info(L.OOC); return end
        SetupMacros()
        preview = not preview
        Refresh()
    elseif message == "reset" then
        if InCombatLockdown() then Info(L.OOC); return end
        SentinelMarkersDB = SentinelMarkersDB or {}
        SentinelMarkersDB.position = nil
        panel:ClearAllPoints()
        panel:SetPoint("CENTER", UIParent, "CENTER", 0, -180)
    elseif message == "auto" then
        preview = false
        Refresh()
    else
        Info(L.HELP)
    end
end
